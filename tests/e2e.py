XLSX_JS = open('node_modules/xlsx/dist/xlsx.full.min.js').read()
errs = []
async def setup(ctx):
    async def route(r):
        u = r.request.url
        if 'cdnjs' in u and 'xlsx' in u: await r.fulfill(body=XLSX_JS, content_type='application/javascript')
        elif u.startswith('file://'): await r.continue_()
        else: await r.abort()
    await ctx.route('**/*', route)
